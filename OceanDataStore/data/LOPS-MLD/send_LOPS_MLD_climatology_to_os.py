# send_LOPS_MLD_climatology_to_os.py
#
# Script to write LOPS MLD climatologies to Icechunk
# repository in JASMIN cloud object storage.
#
# Created By: Ollie Tooth (oliver.tooth@noc.ac.uk)
# =========================================================
import logging

import numpy as np
import xarray as xr
import zarr

from OceanDataStore.cli import initialise_logging, send_to_icechunk
from OceanDataStore.data.utils import (
    compute_cell_area,
    compute_dx,
    compute_dy,
)

logger = logging.getLogger(__name__)


def main():
    # ========== Initialise OceanDataStore Logging ========== #
    initialise_logging()
    logger.info("In Progress: Sending LOPS-MLD Climatologies to JASMIN Object Store.")

    # ========== Prepare Data ========== #
    filepath = "/dssgfs01/scratch/otooth/npd_data/observations/LOPS-MLD/mld_dr003_ref10m_v2023.nc"
    ds = xr.open_dataset(filepath)

    # Use OceanDataStore standard variable names for coordinates and climatology bounds
    ds = ds.rename({"lon": "longitude",
                    "lat": "latitude",
                    "time": "month"
                    })

    # Update time coordinate:
    start_year = 1970
    end_year = 2021
    ds = ds.assign_coords({'month': np.arange(1, 13)})

    # Add time bounds to reflect climatological period:
    ds['time_bnds'] = xr.DataArray(
        np.zeros((ds['month'].size, 2), dtype='datetime64[ns]'),
        dims=('month', 'bnds'),
        coords={'month': ds['month']},
    )
    ds['time_bnds'].data[:, 0] = (np.datetime64(f'{start_year}-01', 'M') + (np.timedelta64(1, 'M') * np.arange(ds['month'].size))).astype('datetime64[ns]')
    ds['time_bnds'].data[:, 1] = (np.datetime64(f'{end_year}-01', 'M') + (np.timedelta64(1, 'M') * np.arange(ds['month'].size))).astype('datetime64[ns]')

    # Add ancillary variables:
    ds['dx'] = compute_dx(ds)
    ds['dy'] = compute_dy(ds)
    ds['cell_area'] = compute_cell_area(ds)

    logger.info("Completed: Prepared LOPS-MLD climatology dataset with ancillary variables.")

    # ========== CF Attributes ========== #
    ds.attrs.clear()
    ds = ds.assign_attrs({
        "Conventions": "CF-1.6",
        "title": f"Monthly climatology of the oceanic mixed layer depth (mld_dr003_ref10m.nc, v2023) ({start_year}-{end_year}).",
        "description": "Mixed layer depth climatology computed with a density threshold criterion of 0.03 kg/m3 from 10 m depth value based on about 7.3 million casts/profiles of temperature and salinity measurements made at sea between January 1970 and December 2021.",
        "source": "This MLD climatology is generated by monthly mapping (OI/kriging) of MLD estimations from individual ocean casts/profiles measuring pressure/depth, temperature and salinity, and coming from the ARGO program (argo.ucsd.edu ; argo.net), and from the NOAA NCEI World Ocean Database (www.ncei.noaa.gov/products/world-ocean-database): CTD, APB (sea mammals), OSD (bottles), MRB (moored buoys including e.g. TAO array), GLD (gliders), UOR (undulating ocean recorder, e.g. seasor), DRB (drifting buoys, including e.g. Ice Tethered Profilers). Original L3 file timestamp: Tue Jul 11 18:48:39 2023.",
        "dataset_type": "observation",
        "product_type": "climatology",
        "product_version": "2023",
        "institution": "LOPS Laboratory (IFREMER, Univ. of Brest, CNRS, IRD), Brest, France",
        "citation": "de Boyer montégut Clément (2023). Mixed layer depth climatology computed with a density threshold criterion of 0.03kg/m3 from 10 m depth value. SEANOE. https://doi.org/10.17882/91774",
        "references": "de Boyer montegut Clement, Madec Gurvan, Fischer Albert S., Lazar Alban, Iudicone Daniele (2004). Mixed layer depth over the global ocean: An examination of profile data and a profile-based climatology. Journal Of Geophysical Research-oceans. 109 (C12/C12003). 1-20. Amer Geophysical Union. https://doi.org/10.1029/2004JC002378",
        "acknowledgement": "The production of this MLD climatology relies on individual profile measurements of pressure/depth, temperature and salinity made at sea. Those data come from several sources. The Argo data were collected and made freely available by the International Argo Program and the national programs that contribute to it. (https://argo.ucsd.edu, https://www.ocean-ops.org). The Argo Program is part of the Global Ocean Observing System. All other kind of casts/profiles comes from the World Ocean Database (WOD, Boyer et al. 2018). First released in 1994, and updated regularly since then, the World Ocean Database represents the world's largest collection of vertical profile data of ocean characteristics available internationally without restriction.",
        "license": "Mixed layer depth climatology data were obtained from https://doi.org/10.17882/91774 and are provided under a Creative Commons Attribution 4.0 International (CC BY 4.0) License https://creativecommons.org/licenses/by/4.0/",
        "doi": "https://doi.org/10.17882/91774",
        "platform": "gr",
        "horizontal_grid_type": "regular rectilinear",
        "horizontal_grid_resolution": "1 degree",
        "aggregation": "mean",
        "aggregation_frequency": "monthly",
        "status": "completed",
        "update_frequency": "None",
        "bbox": "[-180.0, 180.0, -90.0, 90.0]",
    })
    logger.info(f"Completed: Added CF-compliant global attributes to LOPS-MLD {start_year}-{end_year} monthly climatology dataset.")

    # ========== Send to Icechunk Repository ========== #
    logger.info(f"In Progress: Sending LOPS-MLD {start_year}-{end_year} monthly climatology to Icechunk Repository...")
    store_credentials_json = ".../credentials/jasmin_os_credentials.json"
    bucket = "lops"
    prefix = f"lops_mld_{start_year}_{end_year}_monthly_climatology"
    exists = False
    branch = "main"
    commit_message = f"Added LOPS-MLD {start_year}-{end_year} monthly climatology."
    variable_commits = True
    
    # Optimise chunk sizes for spatial analysis:
    ds = ds.chunk({'longitude':360, 'latitude': 180})

    # Update variable encodings:
    blosccodec = zarr.codecs.BloscCodec(cname="zstd", clevel=3, shuffle="shuffle")
    for var in list(ds.data_vars) + list(ds.coords):
        ds[var].encoding.clear()
        ds[var].encoding['compressors'] = [blosccodec]

    send_to_icechunk(
        file=ds,
        bucket=bucket,
        object_prefix=prefix,
        store_credentials_json=store_credentials_json,
        exists=exists,
        branch=branch,
        commit_message=commit_message,
        variable_commits=variable_commits,
        dask_config_kwargs=None,
        dask_cluster_kwargs=None,
        )

    logger.info(f"Completed: Sent LOPS-MLD {start_year}-{end_year} monthly climatology to Icechunk Repository.")

if __name__ == "__main__":
    main()
